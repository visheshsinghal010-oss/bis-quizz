def get_quiz_questions(count=30):
    """
    Returns `count` questions formatted for participants.
    Excludes the correct answer key so participants cannot inspect client JS.
    """
    import random
    selected = random.sample(BIS_QUESTIONS, min(count, len(BIS_QUESTIONS)))
    
    # Return questions with sanitized payload (without answer key)
    sanitized = []
    for idx, q in enumerate(selected):
        sanitized.append({
            "question_index": idx + 1,
            "id": q["id"],
            "question": q["question"],
            "options": q["options"]
        })
    return sanitized, [q["id"] for q in selected]


def grade_answers(question_ids, participant_answers, time_spent_seconds, max_time_seconds=1200):
    """
    Evaluates participant answers against true keys.
    Computes:
    - Base score (100 pts per correct answer)
    - Speed bonus: Up to 50 pts per correct answer based on remaining time!
    """
    id_map = {q["id"]: q for q in BIS_QUESTIONS}
    correct_count = 0
    total_questions = len(question_ids)
    details = []

    for q_id in question_ids:
        q_obj = id_map.get(q_id)
        if not q_obj:
            continue
        user_answer = participant_answers.get(str(q_id))
        is_correct = (user_answer is not None and int(user_answer) == q_obj["answer"])
        if is_correct:
            correct_count += 1
        
        details.append({
            "id": q_id,
            "question": q_obj["question"],
            "user_answer": user_answer,
            "correct_answer": q_obj["answer"],
            "is_correct": is_correct,
            "explanation": q_obj["explanation"]
        })

    # Base points: 100 per correct answer
    base_points = correct_count * 100

    # Speed Bonus Calculation:
    # 20 minutes = 1200 seconds.
    # The faster the student finishes, the higher the remaining seconds.
    # Speed bonus is proportional to remaining time and accuracy:
    # Example: If student gets 25 correct and finishes in 600s (half time):
    # remaining = 600s -> bonus = (600 / 1200) * 1000 * (25 / 30) = 417 bonus points!
    remaining_seconds = max(0, max_time_seconds - time_spent_seconds)
    time_ratio = remaining_seconds / max_time_seconds
    accuracy_ratio = correct_count / total_questions if total_questions > 0 else 0
    
    # Speed bonus up to 1500 points
    speed_bonus = round(time_ratio * 1500 * accuracy_ratio)
    total_points = base_points + speed_bonus

    return {
        "total_questions": total_questions,
        "correct_count": correct_count,
        "incorrect_count": total_questions - correct_count,
        "base_points": base_points,
        "speed_bonus": speed_bonus,
        "total_points": total_points,
        "time_spent_seconds": time_spent_seconds,
        "remaining_seconds": remaining_seconds,
        "details": details
    }
